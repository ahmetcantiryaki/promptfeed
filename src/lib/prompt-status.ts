/**
 * Presentation layer for the three prompt-status tiers (see migration 0016 and
 * the `PromptStatus` union in `@/types/domain`). This is the SINGLE source of
 * truth for every label, helper line, caveat, count label, and color used by
 * the badge, feed card, detail modal, canonical prompt page, filter surfaces,
 * and stats strip — so the trust language never drifts between them.
 *
 * Tailwind note: every className here is a complete literal string (no runtime
 * interpolation of color names), so the JIT compiler can see and emit them.
 */

import type { PromptStatus } from "@/types/domain";
import { isPromptStatus, DEFAULT_PROMPT_STATUS } from "@/types/domain";

export interface PromptStatusMeta {
  /** Full badge label, e.g. "Verified Prompt". */
  label: string;
  /** Short label for count chips, e.g. "Verified" / "References" / "Estimated". */
  countLabel: string;
  /** Section header above the prompt body, e.g. "Prompt" / "Estimated Prompt". */
  heading: string;
  /** One-line helper under the prompt-section header. */
  helper: string;
  /** Copy-button label. `null` means the tier is NOT copyable (reference). */
  copyLabel: string | null;
  /** Secondary caveat shown near the heading/empty-state. `null` when none. */
  caveat: string | null;
  /** Empty-state title when there is no prompt to show (reference only). */
  emptyTitle: string | null;
  /** Dot swatch — the only color the over-media (glass) badge carries. */
  dotClass: string;
  /** On-surface tinted pill: border + bg + text together. */
  tintedClass: string;
}

