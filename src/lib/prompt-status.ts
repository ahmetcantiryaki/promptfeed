/** Narrow the DB's raw `prompt_status` text to a known tier (default verified). */
export function promptStatusOf(raw: string | null | undefined): PromptStatus {
  return isPromptStatus(raw) ? raw : DEFAULT_PROMPT_STATUS;
}
